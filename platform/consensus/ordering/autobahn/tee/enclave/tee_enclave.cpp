sgx_status_t ecall_init(uint32_t self_id, uint32_t n, uint32_t f,
                        uint32_t mode, const uint8_t* group_seed) {
  if (g_initialized) return SGX_ERROR_INVALID_STATE;
  if (n == 0 || n > PEARL_MAX_REPLICAS || self_id == 0 || self_id > n ||
      mode > kModeBOF) {
    return SGX_ERROR_INVALID_PARAMETER;
  }
  sgx_status_t ret = Sha256(group_seed, 32, g_key);
  if (ret != SGX_SUCCESS) return ret;

  g_self = self_id;
  g_n = n;
  g_f = f;
  g_mode = static_cast<Mode>(mode);
  memset(g_last_car_hash, 0, sizeof(g_last_car_hash));

  g_history = new std::unordered_set<std::string>();
  g_ol_unsealed = new std::map<int64_t, std::string>();
  g_ol_own_ts = new std::unordered_map<std::string, int64_t>();
  g_ol_keys = new std::unordered_map<std::string, int64_t>();
  g_forget_on_seal = new std::unordered_set<std::string>();
  g_open_items = new std::vector<std::pair<std::string, bool>>();
  g_window_open = new std::unordered_map<std::string, int64_t>();
  g_open_count = new std::map<int64_t, int>();
  g_car_max = new std::map<int64_t, std::vector<Announcement>>();
  g_m = new std::vector<Announcement>(n + 1);
  g_initialized = true;
  return SGX_SUCCESS;
}

sgx_status_t ecall_ol_attest(const uint8_t* id, int64_t ts,
                             uint8_t* tag_out) {
  if (!g_initialized || g_mode != kModeOL) return SGX_ERROR_INVALID_STATE;
  std::string key = Key(id);
  if (g_history->count(key) || !FreshTimestamp(ts)) {
    return SGX_ERROR_INVALID_PARAMETER;
  }
  g_history->insert(key);
  (*g_ol_unsealed)[ts] = key;
  (*g_ol_own_ts)[key] = ts;

  uint8_t msg[PEARL_INDICATOR_MSG_LEN];
  pearl_indicator_msg(msg, PEARL_DOM_OL_TIMESTAMP, g_self, id, ts);
  return Tag(msg, sizeof(msg), tag_out);
}

sgx_status_t ecall_ol_local_key(const uint8_t* id, const uint8_t* records,
                                uint32_t rec_len, int64_t* key_out) {
  if (!g_initialized || g_mode != kModeOL) return SGX_ERROR_INVALID_STATE;
  if (rec_len % PEARL_SIGNED_TS_REC != 0) return SGX_ERROR_INVALID_PARAMETER;
  std::string key = Key(id);
  /* Only for a transaction this enclave attested and has not keyed yet. */
  if (g_ol_own_ts->find(key) == g_ol_own_ts->end() ||
      g_ol_keys->find(key) != g_ol_keys->end()) {
    return SGX_ERROR_INVALID_PARAMETER;
  }

  std::vector<int64_t> values;
  std::vector<bool> seen(g_n + 1, false);
  uint32_t count = rec_len / PEARL_SIGNED_TS_REC;
  for (uint32_t i = 0; i < count; i++) {
    const uint8_t* rec = records + i * PEARL_SIGNED_TS_REC;
    uint32_t signer = pearl_get_u32(rec);
    int64_t ts = pearl_get_i64(rec + 4);
    if (signer == 0 || signer > g_n || seen[signer]) continue;
    uint8_t msg[PEARL_INDICATOR_MSG_LEN];
    pearl_indicator_msg(msg, PEARL_DOM_OL_TIMESTAMP, signer, id, ts);
    if (!TagValid(msg, sizeof(msg), rec + 12)) continue;
    seen[signer] = true;
    values.push_back(ts);
  }
  if (values.size() < g_f + 1) return SGX_ERROR_INVALID_PARAMETER;

  std::sort(values.begin(), values.end());
  int64_t k = values[g_f]; /* (f+1)-th smallest */
  (*g_ol_keys)[key] = k;
  *key_out = k;
  return SGX_SUCCESS;
}

sgx_status_t ecall_ol_seal_car(const uint8_t* items, uint32_t items_len,
                               int64_t* index_out, int64_t* frontier_out,
                               uint8_t* car_hash_out, uint8_t* tag_out) {
  if (!g_initialized || g_mode != kModeOL) return SGX_ERROR_INVALID_STATE;
  if (items_len % PEARL_OL_ITEM_REC != 0) return SGX_ERROR_INVALID_PARAMETER;
  uint32_t count = items_len / PEARL_OL_ITEM_REC;

  /* The enclave controls the Car content: every item must be a transaction
   * it attested, carrying exactly the key it certified. */
  for (uint32_t i = 0; i < count; i++) {
    const uint8_t* rec = items + i * PEARL_OL_ITEM_REC;
    auto it = g_ol_keys->find(Key(rec));
    if (it == g_ol_keys->end() ||
        it->second != pearl_get_i64(rec + PEARL_ID_LEN)) {
      return SGX_ERROR_INVALID_PARAMETER;
    }
  }
  for (uint32_t i = 0; i < count; i++) {
    std::string key = Key(items + i * PEARL_OL_ITEM_REC);
    auto ts = g_ol_own_ts->find(key);
    g_ol_unsealed->erase(ts->second);
    g_ol_own_ts->erase(ts);
    g_ol_keys->erase(key);
    if (g_forget_on_seal->erase(key)) g_history->erase(key);
  }

  uint8_t items_digest[PEARL_ID_LEN];
  sgx_status_t ret = Sha256(items, items_len, items_digest);
  if (ret != SGX_SUCCESS) return ret;

  uint8_t zero[PEARL_ID_LEN] = {0};
  int64_t frontier = CompletionFrontier();
  *frontier_out = frontier;
  return SealCar(PEARL_DOM_CAR_CONTENT_OL, items_digest, frontier, zero,
                 index_out, car_hash_out, tag_out);
}

sgx_status_t ecall_bof_place(const uint8_t* id, int64_t* car_out,
                             uint8_t* tag_out) {
  if (!g_initialized || g_mode != kModeBOF) return SGX_ERROR_INVALID_STATE;
  std::string key = Key(id);
  if (!g_history->insert(key).second) return SGX_ERROR_INVALID_PARAMETER;

  ++g_seq;
  int64_t c = g_open_car;
  g_open_items->push_back(std::make_pair(key, false));
  (*g_window_open)[key] = c;
  (*g_open_count)[c]++;

  uint8_t msg[PEARL_INDICATOR_MSG_LEN];
  pearl_indicator_msg(msg, PEARL_DOM_BOF_PLACEMENT, g_self, id, c);
  *car_out = c;
  return Tag(msg, sizeof(msg), tag_out);
}

sgx_status_t ecall_bof_record_announcements(const uint8_t* id,
                                            const uint8_t* records,
                                            uint32_t rec_len) {
  if (!g_initialized || g_mode != kModeBOF) return SGX_ERROR_INVALID_STATE;
  if (rec_len % PEARL_SIGNED_PLACE_REC != 0) return SGX_ERROR_INVALID_PARAMETER;
  std::string key = Key(id);
  auto open = g_window_open->find(key);
  if (open == g_window_open->end()) return SGX_ERROR_INVALID_PARAMETER;
  int64_t own_car = open->second;

  std::vector<Announcement>& maxima = (*g_car_max)[own_car];
  if (maxima.empty()) maxima.resize(g_n + 1);

  uint32_t count = rec_len / PEARL_SIGNED_PLACE_REC;
  for (uint32_t i = 0; i < count; i++) {
    const uint8_t* rec = records + i * PEARL_SIGNED_PLACE_REC;
    uint32_t signer = pearl_get_u32(rec);
    int64_t c = pearl_get_i64(rec + 4);
    if (signer == 0 || signer > g_n) continue;
    uint8_t msg[PEARL_INDICATOR_MSG_LEN];
    pearl_indicator_msg(msg, PEARL_DOM_BOF_PLACEMENT, signer, id, c);
    if (!TagValid(msg, sizeof(msg), rec + 12)) continue;
    Announcement& a = maxima[signer];
    if (!a.present || c > a.car) {
      a.present = true;
      a.car = c;
      memcpy(a.id, id, PEARL_ID_LEN);
      memcpy(a.tag, rec + 12, PEARL_TAG_LEN);
    }
  }

  g_window_open->erase(open);
  if (--(*g_open_count)[own_car] == 0) g_open_count->erase(own_car);
  return SGX_SUCCESS;
}

sgx_status_t ecall_bof_seal_car(uint8_t* items_out, uint32_t items_cap,
                                uint32_t* num_items_out, int64_t* index_out,
                                int64_t* w_out, uint8_t* m_out, uint32_t m_cap,
                                uint8_t* car_hash_out, uint8_t* tag_out) {
  if (!g_initialized || g_mode != kModeBOF) return SGX_ERROR_INVALID_STATE;
  uint32_t count = (uint32_t)g_open_items->size();
  if ((uint64_t)count * PEARL_BOF_ITEM_REC > items_cap ||
      (uint64_t)g_n * PEARL_M_REC > m_cap) {
    return SGX_ERROR_INVALID_PARAMETER;
  }

  /* Items appear in the order this enclave observed them. */
  for (uint32_t i = 0; i < count; i++) {
    uint8_t* rec = items_out + i * PEARL_BOF_ITEM_REC;
    memcpy(rec, (*g_open_items)[i].first.data(), PEARL_ID_LEN);
    rec[PEARL_ID_LEN] = (*g_open_items)[i].second ? 1 : 0;
  }
  *num_items_out = count;
  g_open_items->clear();
  g_sealed_upto = g_open_car;
  g_open_car++;

  /* w_r: highest sealed position whose transactions all closed their
   * collection window; M_r folds in the announcements of those positions. */
  while (g_w + 1 <= g_sealed_upto &&
         g_open_count->find(g_w + 1) == g_open_count->end()) {
    auto it = g_car_max->find(g_w + 1);
    if (it != g_car_max->end()) {
      for (uint32_t j = 1; j <= g_n; j++) {
        const Announcement& a = it->second[j];
        Announcement& m = (*g_m)[j];
        if (a.present && (!m.present || a.car > m.car)) m = a;
      }
      g_car_max->erase(it);
    }
    g_w++;
  }
  *w_out = g_w;

  memset(m_out, 0, m_cap);
  for (uint32_t j = 1; j <= g_n; j++) {
    uint8_t* rec = m_out + (j - 1) * PEARL_M_REC;
    const Announcement& m = (*g_m)[j];
    if (!m.present) continue;
    rec[0] = 1;
    pearl_put_i64(rec + 1, m.car);
    memcpy(rec + 9, m.id, PEARL_ID_LEN);
    memcpy(rec + 9 + PEARL_ID_LEN, m.tag, PEARL_TAG_LEN);
  }

  uint8_t items_digest[PEARL_ID_LEN], m_digest[PEARL_ID_LEN];
  sgx_status_t ret = Sha256(items_out, count * PEARL_BOF_ITEM_REC, items_digest);
  if (ret != SGX_SUCCESS) return ret;
  ret = Sha256(m_out, g_n * PEARL_M_REC, m_digest);
  if (ret != SGX_SUCCESS) return ret;

  return SealCar(PEARL_DOM_CAR_CONTENT_BOF, items_digest, g_w, m_digest,
                 index_out, car_hash_out, tag_out);
}

sgx_status_t ecall_heartbeat(int64_t ts, uint8_t* id_out,
                             int64_t* value_out) {
  if (!g_initialized) return SGX_ERROR_INVALID_STATE;
  memset(id_out, 0, PEARL_ID_LEN);
  if (g_mode == kModeOL) {
    /* A fresh indicator with no transaction behind it: G_r may pass it. */
    if (!FreshTimestamp(ts)) return SGX_ERROR_INVALID_PARAMETER;
    *value_out = ts;
    return SGX_SUCCESS;
  }
  /* BOF: an enclave-generated no-op item, whose window is trivially closed
   * (no other replica announces it), so later frontiers can cover the Car. */
  uint8_t seed[1 + 4 + 8];
  seed[0] = PEARL_DOM_HEARTBEAT_ID;
  pearl_put_u32(seed + 1, g_self);
  pearl_put_i64(seed + 5, ++g_hb_counter);
  sgx_status_t ret = Sha256(seed, sizeof(seed), id_out);
  if (ret != SGX_SUCCESS) return ret;
  ++g_seq;
  g_open_items->push_back(std::make_pair(Key(id_out), true));
  *value_out = g_open_car;
  return SGX_SUCCESS;
}

sgx_status_t ecall_sign_block(int64_t view, int64_t height,
                              const uint8_t* digest, uint8_t* tag_out) {
  if (!g_initialized) return SGX_ERROR_INVALID_STATE;
  if (view < g_last_block_view ||
      (view == g_last_block_view && height <= g_last_block_height)) {
    return SGX_ERROR_INVALID_PARAMETER;
  }
  g_last_block_view = view;
  g_last_block_height = height;
  uint8_t msg[PEARL_BLOCK_MSG_LEN];
  pearl_block_msg(msg, g_self, view, height, digest);
  return Tag(msg, sizeof(msg), tag_out);
}

/* Enclave garbage collection (Sec. 5.1): once a transaction has been
 * executed, its digest leaves H, so the enclave state stays proportional to
 * the pending transactions.  A resubmission would get a fresh, larger
 * indicator and is discarded against the committed history. */
sgx_status_t ecall_forget(const uint8_t* ids, uint32_t ids_len) {
  if (!g_initialized) return SGX_ERROR_INVALID_STATE;
  if (ids_len % PEARL_ID_LEN != 0) return SGX_ERROR_INVALID_PARAMETER;
  for (uint32_t i = 0; i < ids_len / PEARL_ID_LEN; i++) {
    std::string key = Key(ids + i * PEARL_ID_LEN);
    if (g_mode == kModeOL && g_ol_own_ts->count(key)) {
      g_forget_on_seal->insert(key);
    } else {
      g_history->erase(key);
    }
  }
  return SGX_SUCCESS;
}

sgx_status_t ecall_verify_batch(const uint8_t* records, uint32_t rec_len,
                                uint8_t* ok_out, uint32_t count) {
  if (!g_initialized) return SGX_ERROR_INVALID_STATE;
  uint32_t off = 0;
  for (uint32_t i = 0; i < count; i++) {
    ok_out[i] = 0;
    if (off + 4 > rec_len) return SGX_ERROR_INVALID_PARAMETER;
    uint32_t len = pearl_get_u32(records + off);
    off += 4;
    if ((uint64_t)off + len + PEARL_TAG_LEN > rec_len) {
      return SGX_ERROR_INVALID_PARAMETER;
    }
    ok_out[i] = TagValid(records + off, len, records + off + len) ? 1 : 0;
    off += len + PEARL_TAG_LEN;
  }
  return SGX_SUCCESS;
}
