/* TEE Enclave — trusted code of Pearl (Sec. 5.1-5.2, Alg. 1 and 2).
 *
 * The enclave keeps, in memory its host can neither read nor modify:
 *   - H: identifiers of the transactions it has attested (one attestation
 *     per transaction, so a host cannot equivocate on indicators), pruned
 *     once a transaction is executed;
 *   - OL: the last timestamp it attested (host timestamps must exceed it), the transactions whose local ordering key is
 *     not yet sealed into a Car, and the keys it certified; from these it
 *     derives the completion frontier G_r;
 *   - BOF: its sequence counter, the open Car, and the placement
 *     announcements collected for transactions whose window closed; from
 *     these it derives the reception frontier (w_r, M_r);
 *   - its lane (index and hash of the last sealed Car), so it never seals
 *     two different Cars at one position;
 *   - the (view, height) of the last block it signed.
 *
 * Authentication: tags are HMAC-SHA256 under a key shared by the
 * committee's enclaves (provisioned from `group_seed` at ecall_init; on SGX
 * hardware this provisioning would follow remote attestation).  Tags are
 * therefore verified inside an enclave (ecall_verify_batch), matching
 * TEE.Verify in Alg. 1.  Switching to asymmetric signatures only changes
 * Tag/TagValid.
 */

